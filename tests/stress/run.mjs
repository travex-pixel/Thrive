import { createRequire } from "node:module";
import { readdirSync, readFileSync } from "node:fs";
import { execSync } from "node:child_process";
const require = createRequire(`${process.cwd()}/package.json`);
const { chromium } = require("@playwright/test");
const { unzipSync } = require("fflate");
const dir = process.argv[2];
const mobile = process.argv[3] === "mobile";
const files = readdirSync(dir).map((f) => `${dir}/${f}`);
const t0 = Date.now();
const log = (m) => console.log(`[${((Date.now() - t0) / 1000).toFixed(0)}s] ${m}`);
// Sum of RSS of Chromium renderer processes (MB): what a phone would have to hold for this tab.
const rss = () => { try { return Math.round(Number(execSync("ps -eo rss,args | grep -E 'chrom.*--type=renderer' | grep -v grep | awk '{s+=$1} END {print s}'").toString().trim() || 0) / 1024); } catch { return 0; } };
const browser = await chromium.launch();
const ctx = await browser.newContext(mobile ? { viewport: { width: 393, height: 852 }, isMobile: true, hasTouch: true, acceptDownloads: true } : { acceptDownloads: true });
await ctx.route("**/api/verify**", (r) => r.fulfill({ json: { token: "v1.eyJ2IjoxfQ.c2lnbmF0dXJl" } }));
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
await cdp.send("Performance.enable");
const heap = async () => { const m = (await cdp.send("Performance.getMetrics")).metrics; return Math.round(m.find((x) => x.name === "JSHeapUsedSize").value / 1048576); };
let peakRss = 0, peakHeap = 0, sampling = true;
(async () => { while (sampling) { peakRss = Math.max(peakRss, rss()); try { peakHeap = Math.max(peakHeap, await heap()); } catch {} await new Promise((r) => setTimeout(r, 1000)); } })();
await page.goto(`${process.env.BASE_URL ?? "http://localhost:3200"}/build`);
await page.getByTestId("file-input").setInputFiles(files);
await page.getByText(`${files.length} files added`).waitFor({ timeout: 600000 });
log(`added ${files.length} files`);
await page.waitForFunction(() => !document.querySelector('[aria-label="Checking file"]'), null, { timeout: 1800000, polling: 2000 });
log(`background checks finished (rss peak ${peakRss} MB, heap peak ${peakHeap} MB)`);
await page.getByRole("radio", { name: "2  Sort" }).click();
await page.getByLabel("Group for Bank, loan and pay documents", { exact: true }).selectOption("financial");
await page.getByLabel("Group for Photos", { exact: true }).selectOption("social");
await page.getByRole("button", { name: "Check dates" }).click();
await page.getByRole("button", { name: /dates are right$/ }).click();
log("sorted and dates confirmed");
await page.getByRole("radio", { name: "3  Build" }).click();
const limitCard = await page.getByRole("heading", { name: "Check your attachment limit" }).count();
const planText = await page.locator("#plan-title").locator("..").innerText();
log(`plan: ${planText.split("\n")[1]} | limit check shown: ${limitCard > 0}`);
peakRss = 0; peakHeap = 0;
const b0 = Date.now();
await page.getByRole("button", { name: "Build pack" }).click();
await page.getByRole("heading", { level: 1 }).filter({ hasText: /pack is ready|Over your/ }).waitFor({ timeout: 3600000 });
log(`BUILD ${((Date.now() - b0) / 1000).toFixed(0)}s, renderer rss peak ${peakRss} MB, js heap peak ${peakHeap} MB`);
log(await page.locator("#results-title").locator("..").innerText());
await page.getByRole("button", { name: "Restore a purchase" }).click();
await page.getByLabel("Unlock link").fill("https://x.example/unlock?session_id=cs_test_a1b2c3d4e5f6g7h8");
await page.getByRole("button", { name: "Restore", exact: true }).click();
peakRss = 0;
const dl = page.waitForEvent("download");
await page.getByRole("button", { name: "Download all (.zip)" }).click();
const zipPath = await (await dl).path();
const zip = unzipSync(new Uint8Array(readFileSync(zipPath)));
const sizes = Object.values(zip).map((b) => b.length);
log(`ZIP: ${Object.keys(zip).length} files, largest ${(Math.max(...sizes) / 1e6).toFixed(2)} MB, total ${(sizes.reduce((a, b) => a + b, 0) / 1e6).toFixed(0)} MB, all <= 5,000,000: ${sizes.every((s) => s <= 5000000)}; rss peak during zip ${peakRss} MB`);
const { PDFDocument } = require("pdf-lib");
for (const [name, bytes] of Object.entries(zip)) {
  let pages = "";
  if (name.endsWith(".pdf")) pages = (await PDFDocument.load(bytes, { ignoreEncryption: true })).getPageCount();
  console.log("  ", name, (bytes.length / 1e6).toFixed(2), "MB", pages, "pages");
}
sampling = false;
await browser.close();
